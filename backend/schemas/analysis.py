"""
Pydantic schemas for Analysis endpoints and LLM response validation.
"""

from datetime import datetime
from typing import Literal
from pydantic import BaseModel, Field, model_validator


class SuggestionItem(BaseModel):
    priority: Literal["high", "medium", "low"] = "medium"
    category: str = "general"
    text: str
    quote_from_resume: str | None = Field(default=None, description="Exact phrase from resume related to this fix")
    target_requirement: str | None = Field(default=None, description="Target job requirement related to this fix")


class BulletPair(BaseModel):
    original: str
    improved: str
    explanation: str | None = None


class SectionScores(BaseModel):
    experience: float = Field(ge=0.0, le=100.0, default=80.0)
    skills: float = Field(ge=0.0, le=100.0, default=85.0)
    projects: float = Field(ge=0.0, le=100.0, default=75.0)
    summary: float = Field(ge=0.0, le=100.0, default=80.0)
    education: float = Field(ge=0.0, le=100.0, default=90.0)


class EvidenceClassification(BaseModel):
    supported_by_evidence: list[str] = Field(
        default_factory=list,
        description="Skills found in experience/projects with measurable context"
    )
    mentioned_without_detail: list[str] = Field(
        default_factory=list,
        description="Skills listed in skills section or summary without supporting metrics"
    )
    not_found_in_resume: list[str] = Field(
        default_factory=list,
        description="Skills required by target role that are not detected in the supplied resume"
    )


class LLMAnalysisResult(BaseModel):
    """Schema used to validate JSON generated by the LLM."""
    overall_score: float = Field(ge=0.0, le=100.0, default=0.0)
    ats_score: float = Field(ge=0.0, le=100.0, default=0.0)
    keyword_score: float = Field(ge=0.0, le=100.0, default=0.0)
    impact_score: float = Field(ge=0.0, le=100.0, default=0.0)
    format_score: float = Field(ge=0.0, le=100.0, default=0.0)
    section_scores: SectionScores = Field(default_factory=SectionScores)
    summary: str | None = None
    matched_keywords: list[str] = Field(default_factory=list)
    missing_keywords: list[str] = Field(default_factory=list)
    evidence_classification: EvidenceClassification = Field(default_factory=EvidenceClassification)
    suggestions: list[SuggestionItem] = Field(default_factory=list)
    bullet_improvements: list[BulletPair] = Field(default_factory=list)
    rubric_version: str = "2026.1"


class AnalysisCreate(BaseModel):
    resume_id: int | None = None
    resume_text: str | None = None
    job_title: str | None = None
    job_description: str | None = None

    @model_validator(mode="after")
    def check_resume_source(self):
        if self.resume_id is None and not (self.resume_text and self.resume_text.strip()):
            raise ValueError("Either resume_id or resume_text must be provided")
        return self


class SuggestionOut(BaseModel):
    priority: str
    category: str
    text: str
    quote_from_resume: str | None = None
    target_requirement: str | None = None


class AnalysisOut(BaseModel):
    id: int
    resume_id: int
    job_title: str | None
    job_description: str | None
    overall_score: float
    ats_score: float
    keyword_score: float
    impact_score: float
    format_score: float
    matched_keywords: list[str]
    missing_keywords: list[str]
    suggestions: list[dict]
    result_json: dict = Field(default_factory=dict)
    created_at: datetime

    model_config = {"from_attributes": True}


class AnalysisSummary(BaseModel):
    id: int
    resume_id: int
    job_title: str | None
    overall_score: float
    ats_score: float = 0.0
    keyword_score: float = 0.0
    impact_score: float = 0.0
    format_score: float = 0.0
    matched_keywords: list[str] = Field(default_factory=list)
    missing_keywords: list[str] = Field(default_factory=list)
    created_at: datetime

    model_config = {"from_attributes": True}
