/**
 * Normalizes a skill name string: converts to lowercase, handles alternate names and abbreviations.
 * @param {string} skill
 * @returns {string} normalized key in LEARNING_RESOURCES or empty string
 */
export function normalizeSkillName(skill) {
  if (!skill || typeof skill !== 'string') return '';
  const clean = skill.trim().toLowerCase();

  // 1. Direct alias match
  if (ALIASES[clean]) {
    return ALIASES[clean];
  }

  // 2. Direct key match
  if (LEARNING_RESOURCES[clean]) {
    return clean;
  }

  // 3. Remove spaces and non-alphanumeric except + and #
  const sanitized = clean.replace(/[^a-z0-9+#]/g, '');
  if (ALIASES[sanitized]) {
    return ALIASES[sanitized];
  }
  if (LEARNING_RESOURCES[sanitized]) {
    return sanitized;
  }

  // 4. Try stripping all non-alphanumeric
  const alphaNumOnly = clean.replace(/[^a-z0-9]/g, '');
  if (ALIASES[alphaNumOnly]) {
    return ALIASES[alphaNumOnly];
  }
  if (LEARNING_RESOURCES[alphaNumOnly]) {
    return alphaNumOnly;
  }

  return clean;
}

/**
 * Retrieves the learning recommendation and verified resources for a given skill.
 * If not present, returns a structured fallback.
 * @param {string} skill
 * @returns {{ skill: string, normalizedKey: string, found: boolean, recommendation: string, resources: Array<{ title: string, url: string }> }}
 */
export function getSkillLearningResource(skill) {
  const normalizedKey = normalizeSkillName(skill);
  const resource = LEARNING_RESOURCES[normalizedKey];

  if (resource) {
    return {
      skill,
      normalizedKey,
      found: true,
      recommendation: resource.recommendation,
      resources: resource.resources || []
    };
  }

  return {
    skill,
    normalizedKey,
    found: false,
    recommendation: 'No verified learning resource is available for this skill yet.',
    resources: []
  };
}
